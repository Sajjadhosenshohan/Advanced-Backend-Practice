interface PointA { x: number; y: number }
interface PointB { x: number; y: number }

const a: PointA = { x: 10, y: 20 };
// গঠন এক হওয়ায় অনায়াসে এসাইন করা যায়:
const b: PointB = a;
console.log("✅ ১. Structural Typing এর ফলে নাম ভিন্ন হলেও কম্প্যাটিবল:", b);

// অতিরিক্ত প্রোপার্টি থাকলেও সাব-টাইপিং সাপোর্ট করে:
const point3D = { x: 5, y: 15, z: 25 };
const basePoint: PointA = point3D; // ✅ Valid!
console.log("✅ ২. সাব-টাইপিং দিয়ে অবজেক্ট গ্রহণ:", basePoint.x);

console.log("\n💡 রিভিশন সামারি: টাইপের নাম নয়, গঠন মিললেই টাইপস্ক্রিপ্ট খুশি!\n");
