/**
 * ============================================================================
 * 📌 Q10: Structural vs Nominal Typing 💡
 * ============================================================================
 * 
 * 💡 মূল ধারণা (Core Concept)
 * ────────────────────────────────────────────────────────────────────────────
 * 🔹 Structural Typing (Duck Typing) ➔ "যদি দেখতে হাঁসের মতো হয়, ডাকে হাঁসের মতো আর
 *                                       হাঁটে হাঁসের মতো—তবে এটি একটি হাঁস!"
 *                                       টাইপের নাম কী তা দেখার বিষয় নয়, প্রোপার্টির গঠন (Shape) মিললেই সমতুল্য।
 * 
 * 🔹 Nominal Typing                   ➔ নাম ও আইডি কার্ড ভিত্তিক টাইপিং (Java/C++)।
 *                                       দেখতে অবিকল এক হলেও ক্লাসের নাম ভিন্ন হলে কম্পাইলার রিজেক্ট করবে।
 * 
 * ⚠️ একটা গোপন ফাঁদ (Hidden Trap):
 *   • Structural Typing এর কারণে `type UserId = string;` আর `type OrderId = string;` টাইপস্ক্রিপ্টের চোখে হুবহু এক!
 *   • ফলে ভুল করে অর্ডারের জায়গায় ইউজার আইডি পাস করে দিলে টাইপস্ক্রিপ্ট কোনো এরর দিতে পারে না।
 * 
 * ────────────────────────────────────────────────────────────────────────────
 * 📊 কখন কোনটা কীভাবে কাজ করে? (Comparison Table)
 * ────────────────────────────────────────────────────────────────────────────
 * ┌───────────────────────────┬──────────────────┬──────────────────┬────────────────────────┐
 * │ টাইপিং সিস্টেম            │ ভিত্তি কী?       │ ভাষা             │ সুবিধা ও অসুবিধা       │
 * ├───────────────────────────┼──────────────────┼──────────────────┼────────────────────────┤
 * │ Structural Typing         │ অবজেক্টের শেপ/গঠন│ TypeScript, Go   │ টেস্টিং ও মকিং সহজ     │
 * │ Nominal Typing            │ ক্লাসের নাম/বংশ  │ Java, C#, C++    │ ভুলবশত ডাটা অদলবদল হয় না│
 * └───────────────────────────┴──────────────────┴──────────────────┴────────────────────────┘
 * 
 * 📌 গোল্ডেন রুল:
 *   • টাইপস্ক্রিপ্ট ডিফল্টভাবে Structural। আইডি গুলিয়ে ফেলা বন্ধ করতে **Branded Types** (Q16) ব্যবহার করুন।
 * 
 * ────────────────────────────────────────────────────────────────────────────
 * 🗣️ Interview-তে যেভাবে গুছিয়ে বলবেন (Standard Answer)
 * ────────────────────────────────────────────────────────────────────────────
 * 🇬🇧 English:
 *   "TypeScript uses a structural type system (often called duck typing):
 *    1. Two types are compatible if they have the same shape and properties, regardless of their
 *       explicit names or class hierarchy.
 *    2. This makes mocking in unit tests effortless and aligns with JavaScript's dynamic nature,
 *       though it means type aliases for primitives (like UserId and OrderId) don't prevent mix-ups
 *       unless we use branded types."
 * 
 * 🇧🇩 বাংলায়:
 *   "টাইপস্ক্রিপ্ট স্ট্রাকচারাল টাইপ সিস্টেম (বা ডাক টাইপিং) মেনে চলে:
 *    ১. দুটি অবজেক্টের গঠন ও প্রোপার্টি যদি মিলে যায়, তবে তাদের নাম ভিন্ন হলেও টাইপস্ক্রিপ্ট
 *       তাদের একে অপরের জায়গায় এসাইন করতে দেয়।
 *    ২. এর সুবিধা হলো টেস্টের সময় সহজেই ডেটা মক করা যায়, তবে অসুবিধা হলো সাধারণ প্রিমিটিভ
 *       এলিয়াস (যেমন UserId এবং OrderId) দুটোই string হওয়ায় ভুল করে অদলবদল করলেও কম্পাইলার আটকায় না।"
 * 
 * ────────────────────────────────────────────────────────────────────────────
 * ❓ মোস্ট কমন ২টি ফলো-আপ প্রশ্ন (Follow-up Q&A)
 * ────────────────────────────────────────────────────────────────────────────
 * 🔹 F1: Excess Property Check কী?
 *    👉 উত্তর: কোনো ফাংশনে সরাসরি ইনলাইন অবজেক্ট লিটারাল (`{ x: 1, extra: 2 }`) পাস করলে
 *             টাইপস্ক্রিপ্ট অতিরিক্ত প্রোপার্টি আটকে দেয়। কিন্তু ভ্যারিয়েবলে রেখে পাস করলে স্ট্রাকচারাল ম্যাচ মেনে নেয়।
 * 
 * 🔹 F2: TypeScript এ ক্লাসে কখন Nominal আচরণ দেখা যায়?
 *    👉 উত্তর: ক্লাসের ভেতর 'private' বা 'protected' প্রোপার্টি থাকলে! দুটি ক্লাসে হুবহু একই নামের
 *             প্রাইভেট ফিল্ড থাকলেও তাদের একে অপরে এসাইন করা যায় না।
 * 
 * ────────────────────────────────────────────────────────────────────────────
 * 🏢 প্রজেক্টে কীভাবে ব্যবহার করেছেন (Project Line)
 * ────────────────────────────────────────────────────────────────────────────
 * 🇬🇧 English:
 *   "Structural typing allows me to write lightweight unit tests by passing plain mock objects
 *    matching repository interfaces without having to instantiate heavy ORM classes."
 * 
 * 🇧🇩 বাংলা:
 *   "স্ট্রাকচারাল টাইপিং থাকায় আমি ভারী ডেটাবেজ ওরম ক্লাস ইনিশিয়ালাইজ না করেই শুধুমাত্র একই শেপের
 *    প্লেইন অবজেক্ট পাস করে সহজে ইউনিট টেস্টিং করতে পারি।"
 * 
 * ────────────────────────────────────────────────────────────────────────────
 * 🧪 সেলফ-টেস্ট (Self-Test)
 * ────────────────────────────────────────────────────────────────────────────
 * 1. interface A { x: number } এবং interface B { x: number } কি একে অপরে এসাইন করা যাবে?
 * 2. জাভাতে কি এটা সম্ভব?
 * 
 * 💬 উত্তর:
 * 1. হ্যাঁ, টাইপস্ক্রিপ্টে গঠন এক হওয়ায় সম্পূর্ণ বৈধ।
 * 2. না, জাভাতে Nominal Typing থাকায় টাইপ কনভার্সন এরর দেবে।
 * ============================================================================
 */

