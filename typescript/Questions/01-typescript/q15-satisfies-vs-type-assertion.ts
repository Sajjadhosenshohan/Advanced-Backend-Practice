console.log("==================================================================\n");

type RouteMap = Record<string, { path: string; method: "GET" | "POST" }>;

// satisfies দিয়ে রাউটিং কনফিগ তৈরি:
const AppRoutes = {
  login: { path: "/auth/login", method: "POST" },
  profile: { path: "/user/profile", method: "GET" },
} satisfies RouteMap;

// ১. টাইপ ভ্যালিডেট হয়েছে
// ২. AppRoutes.login এর এক্সাক্ট নাম ও প্রোপার্টি সংরক্ষিত আছে:
console.log("✅ ১. satisfies সংরক্ষিত পাথ:", AppRoutes.login.path);

// ৩. কালার প্যালেটে exact literal ট্র্যাকিং:
type Palette = Record<string, string | number[]>;
const theme = {
  primary: "#3b82f6",
  rgbCoords: [59, 130, 246],
} satisfies Palette;

// primary যে string তা TS ভোলেনি, সরাসরি .toUpperCase() কল করা যাচ্ছে:
console.log("✅ ২. String মেথড নিরাপদে কল:", theme.primary.toUpperCase());

console.log("\n💡 রিভিশন সামারি: টাইপ অক্ষুণ্ণ রেখে নিয়ম মানতে 'satisfies' সেরা!\n");
