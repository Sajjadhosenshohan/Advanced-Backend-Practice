// ১. দ্য চ্যাম্পিয়ন প্যাটার্ন: const object + as const 🏆
export const OrderState = {
  PENDING: "PENDING",
  PROCESSING: "PROCESSING",
  COMPLETED: "COMPLETED",
} as const;

// অবজেক্টের ভ্যালুগুলো থেকে স্বয়ংক্রিয় ইউনিয়ন টাইপ:
export type OrderState = (typeof OrderState)[keyof typeof OrderState];

function updateOrder(status: OrderState) {
  console.log(`✅ ১. Order updated to: ${status}`);
}
updateOrder(OrderState.PROCESSING);

// রানটাইমে সব ভ্যালু পাওয়ার চমৎকার সুবিধা:
const statesList = Object.values(OrderState);
console.log("✅ ২. Object.values() দিয়ে রানটাইম ড্রপডাউন:", statesList);

console.log("\n💡 রিভিশন সামারি: enum বাদ দিন, 'as const' অবজেক্ট বেছে নিন!\n");
