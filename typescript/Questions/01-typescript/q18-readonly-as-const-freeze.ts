// ১. as const দিয়ে ডিপলি লক করা কনফিগ:
const AppConfig = {
  db: {
    port: 5432,
    host: "localhost",
  },
  timeout: 3000,
} as const;

// AppConfig.db.port = 3306; ❌ TS Error: Cannot assign because it is read-only!
console.log("✅ ১. as const Deep Readonly Port:", AppConfig.db.port);

// ২. প্রোডাকশন ব্যাকএন্ড কম্বো (Object.freeze + as const):
const SECURE_CONSTANTS = Object.freeze({
  JWT_LIFETIME: "1h",
  MAX_LOGIN_ATTEMPTS: 5,
} as const);

console.log("✅ ২. প্রোডাকশন কম্বো প্রস্তুত:", SECURE_CONSTANTS.JWT_LIFETIME);

console.log("\n💡 রিভিশন সামারি: কম্পাইলে as const, আর রানটাইমে Object.freeze!\n");
